bool assets_decompress(const uint8_t* src,size_t src_len,uint8_t** dst,size_t* dst_len){
    uint8_t* dbuff = nullptr;

    size_t dsize = ZSTD_getFrameContentSize(src,src_len);

    size_t result;

    if(dsize == ZSTD_CONTENTSIZE_UNKNOWN || dsize == ZSTD_CONTENTSIZE_ERROR){
        gb_printf_error("ZSTD_getFrameContentSize failed");
        goto fail;
    }

    dbuff = (uint8_t*)malloc(dsize);

    if(!dbuff){
        gb_printf_errno(malloc);
        goto fail;
    }

    result = ZSTD_decompress(dbuff,dsize,src,src_len);

    if(ZSTD_isError(result)){
        gb_printf_error("ZSTD_decompress failed");
        goto fail;
    }

    *dst = dbuff;
    *dst_len = dsize;

    return true;

    fail:
    if(dbuff != nullptr) free(dbuff);

    *dst = nullptr;
    *dst_len = 0;
    
    return false;
}

void assets_load_window_icon(SDL_Window* window){
    uint8_t* pixels = nullptr;
    size_t length = 0;

    if(!assets_decompress(icon_compressed_data,icon_compressed_length,&pixels,&length)){
        return;
    }

    SDL_Surface* surface = SDL_CreateRGBSurfaceFrom(
        pixels,
        icon_width,
        icon_height,
        8 * icon_comp,
        icon_width * icon_comp,
        0x000000FF,
        0x0000FF00,
        0x00FF0000,
        0xFF000000
    );

    if(surface){
        SDL_SetWindowIcon(window,surface);
    }
    else{
        gb_printf_error(SDL_GetError());
    }

    SDL_FreeSurface(surface);
    free(pixels);
}